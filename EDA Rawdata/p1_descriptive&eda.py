def describe_cat(df, col, top_n=5):
    freq = df[col].value_counts(dropna=False).head(top_n)
    pct = (df[col].value_counts(normalize=True, dropna=False) * 100).head(top_n)
    return pd.DataFrame({
        'Frequency': freq,
        'Percentage (%)': pct.round(2),
        'Cumulative %': pct.cumsum().round(2)
    })

